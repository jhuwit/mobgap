test_that("mobgap_to_acc converts and resamples", {
  t0 = as.POSIXct("2020-01-01", tz = "UTC")
  df = data.frame(time = t0 + (0:9) / 10, acc_x = 9.80665, acc_y = 0, acc_z = 0)
  out = mobgap_to_acc(df, sample_rate = 10)
  expect_equal(out$x, rep(1, 10))
  expect_equal(attr(out, "sample_rate"), 10)
  attr(df, "sample_rate") = 10
  res = mobgap_to_acc(df, resample_hz = 20)
  expect_equal(attr(res, "sample_rate"), 20)
  expect_equal(nrow(res), 19)
  expect_equal(mobgap_to_acc(df, to_g = FALSE)$x[1], 9.80665)
  expect_error(mobgap_to_acc(data.frame(a = 1), sample_rate = 1))
})

test_that("mobgap_compare_steps computes agreement", {
  t0 = as.POSIXct("2020-01-01", tz = "UTC")
  ref = data.frame(time = t0 + c(0, 60, 180), n_steps = c(10, 20, 30))
  est = data.frame(time = t0 + c(0, 10, 60, 180), steps = c(5, 7, 18, 33))
  out = mobgap_compare_steps(ref, est)
  expect_equal(nrow(out$data), 4)
  expect_equal(out$data$reference, c(10, 20, 0, 30))
  expect_equal(out$data$estimate, c(12, 18, 0, 33))
  expect_equal(out$summary$total_reference, 60)
  expect_equal(out$summary$bias, mean(c(2, -2, 0, 3)))
  expect_true(out$summary$correlation > 0.9)
  expect_true(is.na(out$data$pct_error[3]))
  shifted = mobgap_compare_steps(ref, est, interval = 60, origin = t0 + 30)
  expect_equal(sum(shifted$data$reference), 60)
  expect_error(mobgap_compare_steps(ref[0, ], est[0, ]))
  expect_error(mobgap_compare_steps(data.frame(time = t0), est), "column")
})
