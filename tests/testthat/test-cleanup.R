test_that("uv cleanup only removes new lock files", {
  old = file.path(tempdir(), "uv-old-test.lock")
  file.create(old)
  snap = mobgap_uv_snapshot()
  expect_true(old %in% snap)
  new = file.path(tempdir(), "uv-new-test.lock")
  file.create(new)
  removed = mobgap_cleanup_uv(snap)
  expect_true(new %in% removed)
  expect_false(old %in% removed)
  expect_true(file.exists(old))
  expect_false(file.exists(new))
  expect_true(old %in% mobgap_cleanup_uv())
  expect_false(file.exists(old))
})
